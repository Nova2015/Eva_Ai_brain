"""Safe FreeCAD macro planner.

Only structured, allowlisted CAD operations are accepted. The generated macro is saved
locally for review and is never executed by this module.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import re
import uuid
from pathlib import Path
from typing import Any


_IDENTIFIER = re.compile(r"^[A-Za-z][A-Za-z0-9_]{0,63}$")
_SAFE_FILENAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,100}$")
_ALLOWED_OPERATIONS = {"create_box", "create_cylinder", "boolean_cut", "export_step", "save_document"}


def _identifier(value: Any, field: str) -> str:
    if not isinstance(value, str) or not _IDENTIFIER.fullmatch(value):
        raise ValueError(f"{field} must be a simple CAD identifier")
    return value


def _positive_number(value: Any, field: str) -> float:
    if isinstance(value, bool):
        raise ValueError(f"{field} must be numeric")
    try:
        number = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{field} must be numeric") from exc
    if number <= 0 or not math.isfinite(number):
        raise ValueError(f"{field} must be a finite positive number")
    return number


def _output_root() -> Path:
    configured = os.getenv("EVA_ENGINEERING_OUTPUT_DIR")
    root = Path(configured).expanduser() if configured else (
        Path(__file__).resolve().parents[2] / "data" / "engineering"
    )
    return root.resolve()


def _safe_output_path(root: Path, filename: str, extension: str) -> Path:
    if not isinstance(filename, str) or not _SAFE_FILENAME.fullmatch(filename):
        raise ValueError("Output filename contains unsafe characters")
    if Path(filename).name != filename or ".." in filename:
        raise ValueError("Output filename must not contain a path")
    if Path(filename).suffix.lower() != extension.lower():
        raise ValueError(f"Output filename must use the {extension} extension")
    destination = (root / "exports" / filename).resolve()
    try:
        destination.relative_to(root)
    except ValueError as exc:
        raise ValueError("Output path must remain inside the engineering output directory") from exc
    if destination.exists():
        raise FileExistsError("Output file already exists; EVA will not overwrite it")
    return destination


def build_freecad_macro(
    operations: list[dict[str, Any]],
    *,
    document_name: str = "EVA_Engineering_Model",
    actor_id: str,
    approved: bool,
) -> dict[str, Any]:
    """Generate a reviewed FreeCAD macro from safe structured operations."""
    if not isinstance(actor_id, str) or not actor_id.strip():
        raise ValueError("actor_id is required")
    if approved is not True:
        raise PermissionError("Explicit approval is required to generate a FreeCAD macro")
    document_name = _identifier(document_name, "document_name")
    if not isinstance(operations, list) or not operations:
        raise ValueError("At least one CAD operation is required")
    if len(operations) > 100:
        raise ValueError("A macro may contain at most 100 operations")

    root = _output_root()
    macro_dir = (root / "macros").resolve()
    exports_dir = (root / "exports").resolve()
    for directory in (macro_dir, exports_dir):
        try:
            directory.relative_to(root)
        except ValueError as exc:
            raise ValueError("Engineering output directories must remain inside the configured root") from exc
        directory.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Generated by EVA FreeCAD Adapter. Review before running.",
        "import FreeCAD as App",
        "import Part",
        "import Import",
        f"doc = App.newDocument({json.dumps(document_name)})",
    ]
    known_objects: set[str] = set()
    manifest_operations = []

    for index, operation in enumerate(operations, 1):
        if not isinstance(operation, dict):
            raise ValueError(f"Operation {index} must be an object")
        op = operation.get("op")
        if not isinstance(op, str) or op not in _ALLOWED_OPERATIONS:
            raise ValueError(f"Operation {index} is not allowlisted: {op!r}")

        if op == "create_box":
            name = _identifier(operation.get("name"), f"operation_{index}.name")
            if name in known_objects:
                raise ValueError(f"Duplicate CAD object name: {name}")
            length = _positive_number(operation.get("length_mm"), f"{name}.length_mm")
            width = _positive_number(operation.get("width_mm"), f"{name}.width_mm")
            height = _positive_number(operation.get("height_mm"), f"{name}.height_mm")
            lines.extend([
                f"{name} = doc.addObject('Part::Feature', {json.dumps(name)})",
                f"{name}.Shape = Part.makeBox({length!r}, {width!r}, {height!r})",
                "doc.recompute()",
            ])
            known_objects.add(name)
            manifest_operations.append({
                "op": op, "name": name, "length_mm": length,
                "width_mm": width, "height_mm": height,
            })

        elif op == "create_cylinder":
            name = _identifier(operation.get("name"), f"operation_{index}.name")
            if name in known_objects:
                raise ValueError(f"Duplicate CAD object name: {name}")
            radius = _positive_number(operation.get("radius_mm"), f"{name}.radius_mm")
            height = _positive_number(operation.get("height_mm"), f"{name}.height_mm")
            position = operation.get("position_mm", [0, 0, 0])
            if not isinstance(position, (list, tuple)) or len(position) != 3:
                raise ValueError(f"{name}.position_mm must contain three coordinates")
            coordinates = []
            for axis, value in zip("xyz", position):
                try:
                    coordinate = float(value)
                except (TypeError, ValueError) as exc:
                    raise ValueError(f"{name}.position_mm.{axis} must be numeric") from exc
                if not math.isfinite(coordinate):
                    raise ValueError(f"{name}.position_mm.{axis} must be finite")
                coordinates.append(coordinate)
            lines.extend([
                f"{name} = doc.addObject('Part::Feature', {json.dumps(name)})",
                f"{name}.Shape = Part.makeCylinder({radius!r}, {height!r}, App.Vector({coordinates[0]!r}, {coordinates[1]!r}, {coordinates[2]!r}))",
                "doc.recompute()",
            ])
            known_objects.add(name)
            manifest_operations.append({
                "op": op, "name": name, "radius_mm": radius,
                "height_mm": height, "position_mm": coordinates,
            })

        elif op == "boolean_cut":
            name = _identifier(operation.get("name"), f"operation_{index}.name")
            base = _identifier(operation.get("base"), f"{name}.base")
            tool = _identifier(operation.get("tool"), f"{name}.tool")
            if name in known_objects:
                raise ValueError(f"Duplicate CAD object name: {name}")
            if base not in known_objects or tool not in known_objects:
                raise ValueError("Boolean cut base and tool must reference earlier objects")
            lines.extend([
                f"{name} = doc.addObject('Part::Cut', {json.dumps(name)})",
                f"{name}.Base = doc.getObject({json.dumps(base)})",
                f"{name}.Tool = doc.getObject({json.dumps(tool)})",
                "doc.recompute()",
                f"doc.getObject({json.dumps(base)}).Visibility = False",
                f"doc.getObject({json.dumps(tool)}).Visibility = False",
            ])
            known_objects.add(name)
            manifest_operations.append({"op": op, "name": name, "base": base, "tool": tool})

        elif op == "export_step":
            object_names = operation.get("objects")
            if not isinstance(object_names, list) or not object_names:
                raise ValueError("export_step.objects must be a non-empty list")
            safe_names = [_identifier(value, "export_step.objects[]") for value in object_names]
            if any(name not in known_objects for name in safe_names):
                raise ValueError("STEP export references an unknown CAD object")
            filename = operation.get("filename")
            destination = _safe_output_path(root, filename, ".step")
            lines.extend([
                f"Import.export([doc.getObject({json.dumps(name)}) for name in {json.dumps(safe_names)}], {json.dumps(str(destination))})",
            ])
            manifest_operations.append({
                "op": op, "objects": safe_names,
                "output_file": str(destination),
            })

        elif op == "save_document":
            filename = operation.get("filename")
            destination = _safe_output_path(root, filename, ".FCStd")
            lines.extend([
                "doc.recompute()",
                f"doc.saveAs({json.dumps(str(destination))})",
            ])
            manifest_operations.append({"op": op, "output_file": str(destination)})

    lines.extend(["doc.recompute()", "# End of generated macro. No machine or controller commands are present."])
    macro_text = "\n".join(lines) + "\n"
    macro_id = "EVA-FCAD-" + uuid.uuid4().hex.upper()
    macro_path = macro_dir / f"{macro_id}.FCMacro"
    manifest_path = macro_dir / f"{macro_id}.json"
    macro_path.write_text(macro_text, encoding="utf-8")
    digest = hashlib.sha256(macro_text.encode("utf-8")).hexdigest()
    manifest = {
        "macro_id": macro_id,
        "macro_path": str(macro_path.resolve()),
        "sha256": digest,
        "document_name": document_name,
        "created_by": actor_id,
        "approved_by": actor_id,
        "operations": manifest_operations,
        "status": "prepared_for_review",
        "execution_performed": False,
        "machine_start_allowed": False,
    }
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True), encoding="utf-8")
    return manifest
