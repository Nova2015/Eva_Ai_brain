"""Safe Blender scene planner.

Accepts structured, allowlisted 3D operations and writes a local Blender Python script.
The script is not executed by EVA and does not delete or overwrite existing scenes.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import re
import uuid
from pathlib import Path
from typing import Any


_IDENTIFIER = re.compile(r"^[A-Za-z][A-Za-z0-9_]{0,63}$")
_SAFE_FILENAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,100}$")
_ALLOWED_OPERATIONS = {
    "create_cube", "create_uv_sphere", "create_cylinder",
    "set_material", "add_bevel_modifier", "export_glb", "save_blend",
}


def _identifier(value: Any, field: str) -> str:
    if not isinstance(value, str) or not _IDENTIFIER.fullmatch(value):
        raise ValueError(f"{field} must be a simple Blender identifier")
    return value


def _finite(value: Any, field: str) -> float:
    if isinstance(value, bool):
        raise ValueError(f"{field} must be numeric")
    try:
        number = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{field} must be numeric") from exc
    if not math.isfinite(number):
        raise ValueError(f"{field} must be finite")
    return number


def _positive(value: Any, field: str) -> float:
    number = _finite(value, field)
    if number <= 0:
        raise ValueError(f"{field} must be positive")
    return number


def _vector(value: Any, field: str, *, positive: bool = False) -> list[float]:
    if not isinstance(value, (list, tuple)) or len(value) != 3:
        raise ValueError(f"{field} must contain exactly three coordinates")
    result = [_finite(item, f"{field}[{index}]") for index, item in enumerate(value)]
    if positive and any(item <= 0 for item in result):
        raise ValueError(f"{field} values must be positive")
    return result


def _output_root() -> Path:
    configured = os.getenv("EVA_ENGINEERING_OUTPUT_DIR")
    root = Path(configured).expanduser() if configured else (
        Path(__file__).resolve().parents[2] / "data" / "engineering"
    )
    return root.resolve()


def _safe_output_path(root: Path, filename: str, extension: str) -> Path:
    if not isinstance(filename, str) or not _SAFE_FILENAME.fullmatch(filename):
        raise ValueError("Output filename contains unsafe characters")
    if Path(filename).name != filename or ".." in filename:
        raise ValueError("Output filename must not contain a path")
    if Path(filename).suffix.lower() != extension.lower():
        raise ValueError(f"Output filename must use the {extension} extension")
    destination = (root / "exports" / filename).resolve()
    try:
        destination.relative_to(root)
    except ValueError as exc:
        raise ValueError("Output path must remain inside the engineering output directory") from exc
    if destination.exists():
        raise FileExistsError("Output file already exists; EVA will not overwrite it")
    return destination


def build_blender_script(
    operations: list[dict[str, Any]],
    *,
    scene_name: str = "EVA_Engineering_Scene",
    actor_id: str,
    approved: bool,
) -> dict[str, Any]:
    """Prepare a Blender script from safe structured operations; never runs Blender."""
    if not isinstance(actor_id, str) or not actor_id.strip():
        raise ValueError("actor_id is required")
    if approved is not True:
        raise PermissionError("Explicit approval is required to generate a Blender script")
    scene_name = _identifier(scene_name, "scene_name")
    if not isinstance(operations, list) or not operations:
        raise ValueError("At least one Blender operation is required")
    if len(operations) > 100:
        raise ValueError("A Blender script may contain at most 100 operations")

    root = _output_root()
    script_dir = (root / "blender_scripts").resolve()
    exports_dir = (root / "exports").resolve()
    for directory in (script_dir, exports_dir):
        try:
            directory.relative_to(root)
        except ValueError as exc:
            raise ValueError("Blender output directories must remain inside the configured root") from exc
        directory.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Generated by EVA Blender Adapter. Review before running.",
        "import bpy",
        f"scene = bpy.context.scene",
        f"eva_collection = bpy.data.collections.new({json.dumps(scene_name + '_Generated')})",
        "scene.collection.children.link(eva_collection)",
        "def eva_link_object(obj):",
        "    for collection in list(obj.users_collection):",
        "        collection.objects.unlink(obj)",
        "    eva_collection.objects.link(obj)",
    ]
    known_objects: set[str] = set()
    known_materials: set[str] = set()
    manifest_operations = []

    for index, operation in enumerate(operations, 1):
        if not isinstance(operation, dict):
            raise ValueError(f"Operation {index} must be an object")
        op = operation.get("op")
        if not isinstance(op, str) or op not in _ALLOWED_OPERATIONS:
            raise ValueError(f"Operation {index} is not allowlisted: {op!r}")

        if op in {"create_cube", "create_uv_sphere", "create_cylinder"}:
            name = _identifier(operation.get("name"), f"operation_{index}.name")
            if name in known_objects:
                raise ValueError(f"Duplicate Blender object name: {name}")
            location = _vector(operation.get("location", [0, 0, 0]), f"{name}.location")
            if op == "create_cube":
                size = _positive(operation.get("size"), f"{name}.size")
                lines.extend([
                    f"bpy.ops.mesh.primitive_cube_add(size={size!r}, location={tuple(location)!r})",
                    "obj = bpy.context.object",
                    f"obj.name = {json.dumps(name)}",
                    "eva_link_object(obj)",
                ])
                details = {"op": op, "name": name, "size": size, "location": location}
            elif op == "create_uv_sphere":
                radius = _positive(operation.get("radius"), f"{name}.radius")
                segments = int(operation.get("segments", 32))
                rings = int(operation.get("rings", 16))
                if not 8 <= segments <= 256 or not 4 <= rings <= 128:
                    raise ValueError("Sphere segments/rings are outside safe limits")
                lines.extend([
                    f"bpy.ops.mesh.primitive_uv_sphere_add(segments={segments}, ring_count={rings}, radius={radius!r}, location={tuple(location)!r})",
                    "obj = bpy.context.object",
                    f"obj.name = {json.dumps(name)}",
                    "eva_link_object(obj)",
                ])
                details = {
                    "op": op, "name": name, "radius": radius,
                    "segments": segments, "rings": rings, "location": location,
                }
            else:
                radius = _positive(operation.get("radius"), f"{name}.radius")
                depth = _positive(operation.get("depth"), f"{name}.depth")
                vertices = int(operation.get("vertices", 32))
                if not 8 <= vertices <= 256:
                    raise ValueError("Cylinder vertices must be between 8 and 256")
                lines.extend([
                    f"bpy.ops.mesh.primitive_cylinder_add(vertices={vertices}, radius={radius!r}, depth={depth!r}, location={tuple(location)!r})",
                    "obj = bpy.context.object",
                    f"obj.name = {json.dumps(name)}",
                    "eva_link_object(obj)",
                ])
                details = {
                    "op": op, "name": name, "radius": radius,
                    "depth": depth, "vertices": vertices, "location": location,
                }
            known_objects.add(name)
            manifest_operations.append(details)

        elif op == "set_material":
            object_name = _identifier(operation.get("object"), f"operation_{index}.object")
            material_name = _identifier(operation.get("material"), f"operation_{index}.material")
            if object_name not in known_objects:
                raise ValueError("Material assignment references an unknown Blender object")
            if material_name in known_materials:
                raise ValueError(f"Duplicate Blender material name: {material_name}")
            color = operation.get("base_color", [0.8, 0.8, 0.8, 1.0])
            if not isinstance(color, (list, tuple)) or len(color) != 4:
                raise ValueError("base_color must contain RGBA values")
            rgba = [_finite(value, "base_color") for value in color]
            if any(value < 0 or value > 1 for value in rgba):
                raise ValueError("base_color RGBA values must be between 0 and 1")
            metallic = _finite(operation.get("metallic", 0.0), "metallic")
            roughness = _finite(operation.get("roughness", 0.5), "roughness")
            if not 0 <= metallic <= 1 or not 0 <= roughness <= 1:
                raise ValueError("metallic and roughness must be between 0 and 1")
            lines.extend([
                f"mat = bpy.data.materials.new({json.dumps(material_name)})",
                "mat.use_nodes = True",
                f"mat.diffuse_color = {tuple(rgba)!r}",
                "bsdf = mat.node_tree.nodes.get('Principled BSDF')",
                f"bsdf.inputs['Base Color'].default_value = {tuple(rgba)!r}",
                f"bsdf.inputs['Metallic'].default_value = {metallic!r}",
                f"bsdf.inputs['Roughness'].default_value = {roughness!r}",
                f"bpy.data.objects[{json.dumps(object_name)}].data.materials.append(mat)",
            ])
            known_materials.add(material_name)
            manifest_operations.append({
                "op": op, "object": object_name, "material": material_name,
                "base_color": rgba, "metallic": metallic, "roughness": roughness,
            })

        elif op == "add_bevel_modifier":
            object_name = _identifier(operation.get("object"), f"operation_{index}.object")
            if object_name not in known_objects:
                raise ValueError("Bevel modifier references an unknown Blender object")
            width = _positive(operation.get("width"), f"{object_name}.bevel_width")
            segments = int(operation.get("segments", 2))
            if not 1 <= segments <= 12:
                raise ValueError("Bevel segments must be between 1 and 12")
            lines.extend([
                f"obj = bpy.data.objects[{json.dumps(object_name)}]",
                f"modifier = obj.modifiers.new(name='EVA_Bevel', type='BEVEL')",
                f"modifier.width = {width!r}",
                f"modifier.segments = {segments}",
            ])
            manifest_operations.append({
                "op": op, "object": object_name, "width": width, "segments": segments,
            })

        elif op == "export_glb":
            object_names = operation.get("objects")
            if not isinstance(object_names, list) or not object_names:
                raise ValueError("export_glb.objects must be a non-empty list")
            safe_names = [_identifier(value, "export_glb.objects[]") for value in object_names]
            if any(name not in known_objects for name in safe_names):
                raise ValueError("GLB export references an unknown Blender object")
            filename = operation.get("filename")
            destination = _safe_output_path(root, filename, ".glb")
            lines.extend([
                "bpy.ops.object.select_all(action='DESELECT')",
                f"export_objects = [bpy.data.objects[{json.dumps(name)}] for name in {json.dumps(safe_names)}]",
                "for obj in export_objects:",
                "    obj.select_set(True)",
                "bpy.context.view_layer.objects.active = export_objects[0]",
                f"bpy.ops.export_scene.gltf(filepath={json.dumps(str(destination))}, export_format='GLB', use_selection=True)",
                "bpy.ops.object.select_all(action='DESELECT')",
            ])
            manifest_operations.append({
                "op": op, "objects": safe_names, "output_file": str(destination),
            })

        elif op == "save_blend":
            filename = operation.get("filename")
            destination = _safe_output_path(root, filename, ".blend")
            lines.append(f"bpy.ops.wm.save_as_mainfile(filepath={json.dumps(str(destination))})")
            manifest_operations.append({"op": op, "output_file": str(destination)})

    lines.append("# End of generated script. No existing scene is deleted and no script is executed by EVA.")
    script_text = "\n".join(lines) + "\n"
    script_id = "EVA-BLENDER-" + uuid.uuid4().hex.upper()
    script_path = script_dir / f"{script_id}.py"
    manifest_path = script_dir / f"{script_id}.json"
    script_path.write_text(script_text, encoding="utf-8")
    digest = hashlib.sha256(script_text.encode("utf-8")).hexdigest()
    manifest = {
        "script_id": script_id,
        "script_path": str(script_path.resolve()),
        "sha256": digest,
        "scene_name": scene_name,
        "created_by": actor_id,
        "approved_by": actor_id,
        "operations": manifest_operations,
        "status": "prepared_for_review",
        "execution_performed": False,
        "machine_start_allowed": False,
    }
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True), encoding="utf-8")
    return manifest
