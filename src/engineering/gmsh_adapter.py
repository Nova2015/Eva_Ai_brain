"""Safe Gmsh mesh-script generator for governed STEP inputs.

Creates a local .geo script only. It does not launch Gmsh or produce a mesh.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import uuid
from pathlib import Path
from typing import Any

from .domain_validation import validate_step_file
from .tool_registry import _db_path
from ..data_governance import authorize_data_action, get_record, sha256_file


_ALLOWED_3D_ALGORITHMS = {1, 4, 7, 10}


def _positive(value: Any, field: str) -> float:
    if isinstance(value, bool):
        raise ValueError(f"{field} must be numeric")
    try:
        number = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{field} must be numeric") from exc
    if not math.isfinite(number) or number <= 0:
        raise ValueError(f"{field} must be finite and positive")
    return number


def _output_dir() -> Path:
    configured = os.getenv("EVA_ENGINEERING_OUTPUT_DIR")
    root = Path(configured).expanduser() if configured else (
        Path(__file__).resolve().parents[2] / "data" / "engineering"
    )
    root = root.resolve()
    target = (root / "mesh_scripts").resolve()
    try:
        target.relative_to(root)
    except ValueError as exc:
        raise ValueError("Mesh script directory must remain inside engineering output root") from exc
    target.mkdir(parents=True, exist_ok=True)
    return target


def _gmsh_quote(path: Path) -> str:
    value = str(path.resolve()).replace("\\", "/")
    if any(ord(char) < 32 for char in value):
        raise ValueError("Geometry path contains control characters")
    return '"' + value.replace('"', '\\"') + '"'


def build_gmsh_mesh_script(
    *,
    data_id: str,
    owner_id: str,
    workspace_id: str,
    actor_id: str,
    mesh_size_min_mm: float,
    mesh_size_max_mm: float,
    algorithm_3d: int = 10,
    element_order: int = 1,
    approved: bool,
) -> dict[str, Any]:
    if approved is not True:
        raise PermissionError("Explicit approval is required to prepare a Gmsh mesh script")
    if not actor_id or actor_id != owner_id:
        raise PermissionError("Only the authenticated data owner may prepare this mesh script")
    if not authorize_data_action(
        data_id, actor_id=actor_id, workspace_id=workspace_id, action="execute"
    ):
        raise PermissionError("Execute permission is required for the governed CAD input")

    record = get_record(data_id, owner_id=owner_id, workspace_id=workspace_id)
    if record is None:
        raise KeyError(f"Governed Data ID not found: {data_id}")
    geometry_path = Path(record["file_path"]).expanduser().resolve(strict=True)
    if not geometry_path.is_file():
        raise ValueError("Governed STEP geometry is not a regular file")
    if geometry_path.suffix.lower() not in {".step", ".stp"}:
        raise ValueError("Gmsh CAD mesh input must be a STEP or STP file")
    digest = sha256_file(geometry_path)
    if digest != record["sha256"]:
        raise ValueError("Governed STEP input SHA-256 no longer matches its Data ID")
    geometry_validation = validate_step_file(geometry_path)
    if not geometry_validation["ok"]:
        raise ValueError("STEP header validation failed: " + "; ".join(geometry_validation["issues"]))

    size_min = _positive(mesh_size_min_mm, "mesh_size_min_mm")
    size_max = _positive(mesh_size_max_mm, "mesh_size_max_mm")
    if size_min > size_max:
        raise ValueError("mesh_size_min_mm cannot exceed mesh_size_max_mm")
    if isinstance(algorithm_3d, bool) or algorithm_3d not in _ALLOWED_3D_ALGORITHMS:
        raise ValueError("Unsupported 3D mesh algorithm; choose one of 1, 4, 7 or 10")
    if isinstance(element_order, bool) or element_order not in {1, 2}:
        raise ValueError("element_order must be 1 or 2")

    output_dir = _output_dir()
    script_id = "EVA-GMSH-" + uuid.uuid4().hex.upper()
    mesh_path = (output_dir / f"{script_id}.msh").resolve()
    script_path = (output_dir / f"{script_id}.geo").resolve()
    for candidate in (mesh_path, script_path):
        try:
            candidate.relative_to(output_dir)
        except ValueError as exc:
            raise ValueError("Gmsh outputs must remain inside the mesh script directory") from exc
        if candidate.exists():
            raise FileExistsError("Gmsh output already exists; refusing to overwrite")

    script = "\n".join([
        "// Generated by EVA Gmsh Adapter. Review before running.",
        'SetFactory("OpenCASCADE");',
        f"Merge {_gmsh_quote(geometry_path)};",
        f"Mesh.CharacteristicLengthMin = {size_min:.12g};",
        f"Mesh.CharacteristicLengthMax = {size_max:.12g};",
        f"Mesh.Algorithm3D = {algorithm_3d};",
        f"Mesh.ElementOrder = {element_order};",
        "Mesh 3;",
        f"Save {_gmsh_quote(mesh_path)};",
        "// No solver or physical machine is started by EVA.",
        "",
    ])
    script_path.write_text(script, encoding="utf-8")
    digest_script = hashlib.sha256(script.encode("utf-8")).hexdigest()
    manifest = {
        "script_id": script_id,
        "script_path": str(script_path),
        "mesh_output_path": str(mesh_path),
        "sha256": digest_script,
        "source_data_id": data_id,
        "source_sha256": digest,
        "geometry_validation": geometry_validation,
        "mesh_size_min_mm": size_min,
        "mesh_size_max_mm": size_max,
        "algorithm_3d": algorithm_3d,
        "element_order": element_order,
        "status": "prepared_for_review",
        "created_by": actor_id,
        "approved_by": actor_id,
        "mesh_generation_performed": False,
        "engineering_approval": "not_granted",
    }
    manifest_path = output_dir / f"{script_id}.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True), encoding="utf-8")
    return manifest
