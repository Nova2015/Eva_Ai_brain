"""
EVA frontend: बाहेरच्या CDN/फॉन्ट फाइल्स स्थानिक करतो (इंटरनेट बंद असतानाही UI चालावा म्हणून).

हे एकदाच चालवा, इंटरनेट चालू असताना (npm पॅकेजेस उतरवण्यासाठी):
    cd D:\\Eva_Ai_brain\\frontend
    python localize_frontend_assets.py

काय करतो:
  1. katex 0.16.9, mermaid 10.9.1, jszip 3.10.1, Inter आणि Space Mono फॉन्ट्स npm मधून घेतो
     आणि public\\vendor\\ मध्ये ठेवतो.
  2. 4 जागी बाहेरचे URL स्थानिक URL ने बदलतो (प्रत्येक फाइलची .bak प्रत बनवतो):
       public\\index.html  (katex css + js, आणि फॉन्ट css जोडतो)
       src\\App.css        (Google Fonts @import काढतो)
       src\\pages\\Chat.js  (mermaid)
       src\\pages\\Upload.js (jszip)
बदल बाइट-पातळीवर होतात, म्हणून फाइल्सचे encoding बिघडत नाही. पुन्हा चालवले तरी चालते.
नंतर फ्रंटएंड restart (npm start) किंवा पुन्हा build करा.
"""
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.cwd()
PUBLIC = ROOT / "public"
SRC = ROOT / "src"
VENDOR = PUBLIC / "vendor"

PACKAGES = ["katex@0.16.9", "mermaid@10.9.1", "jszip@3.10.1", "@fontsource/inter", "@fontsource/space-mono"]

# (फाइल, जुने bytes, नवे bytes)
EDITS = [
    (PUBLIC / "index.html",
     b"https://cdn.jsdelivr.net/npm/katex@0.16.9/dist/katex.min.css",
     b"%PUBLIC_URL%/vendor/katex/katex.min.css"),
    (PUBLIC / "index.html",
     b"https://cdn.jsdelivr.net/npm/katex@0.16.9/dist/katex.min.js",
     b"%PUBLIC_URL%/vendor/katex/katex.min.js"),
    (SRC / "pages" / "Chat.js",
     b"'https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.min.js'",
     b"(process.env.PUBLIC_URL || '') + '/vendor/mermaid/mermaid.min.js'"),
    (SRC / "pages" / "Upload.js",
     b"'https://cdnjs.cloudflare.com/ajax/libs/jszip/3.10.1/jszip.min.js'",
     b"(process.env.PUBLIC_URL || '') + '/vendor/jszip/jszip.min.js'"),
]
GOOGLE_FONTS_IMPORT = b"@import url('https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800;900&family=Space+Mono:wght@400;700&display=swap');"
FONT_LINK = b'<link rel="stylesheet" href="%PUBLIC_URL%/vendor/fonts/fonts.css">'


def npm_pack(workdir: Path):
    npm = shutil.which("npm")
    if not npm:
        sys.exit("npm सापडले नाही. Node.js स्थापित असावे.")
    print("npm पॅकेजेस उतरवत आहे (इंटरनेट लागते)...")
    r = subprocess.run([npm, "pack", "--silent", *PACKAGES], cwd=workdir,
                       capture_output=True, text=True, shell=(os.name == "nt"))
    if r.returncode != 0:
        sys.exit("npm pack अपयशी:\n" + (r.stderr or r.stdout))
    out = {}
    for tgz in workdir.glob("*.tgz"):
        dest = workdir / ("x_" + tgz.stem)
        with tarfile.open(tgz) as t:
            t.extractall(dest)
        out[tgz.name] = dest / "package"
    return out


def find(pkgs, prefix):
    for name, path in pkgs.items():
        if name.startswith(prefix):
            return path
    sys.exit(f"पॅकेज सापडले नाही: {prefix}")


def copy(src: Path, dst: Path):
    if not src.exists():
        sys.exit(f"अपेक्षित फाइल नाही: {src}")
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)


def install_assets(pkgs):
    katex = find(pkgs, "katex-")
    copy(katex / "dist" / "katex.min.css", VENDOR / "katex" / "katex.min.css")
    copy(katex / "dist" / "katex.min.js", VENDOR / "katex" / "katex.min.js")
    fonts_dst = VENDOR / "katex" / "fonts"
    fonts_dst.mkdir(parents=True, exist_ok=True)
    for f in (katex / "dist" / "fonts").iterdir():
        shutil.copy2(f, fonts_dst / f.name)
    copy(find(pkgs, "mermaid-") / "dist" / "mermaid.min.js", VENDOR / "mermaid" / "mermaid.min.js")
    copy(find(pkgs, "jszip-") / "dist" / "jszip.min.js", VENDOR / "jszip" / "jszip.min.js")

    inter = find(pkgs, "fontsource-inter-") / "files"
    mono = find(pkgs, "fontsource-space-mono-") / "files"
    css = ["/* EVA local fonts (Inter, Space Mono) - generated by localize_frontend_assets.py */"]
    for fam, folder, slug, weights in (("Inter", inter, "inter", (400, 500, 600, 700, 800, 900)),
                                       ("Space Mono", mono, "space-mono", (400, 700))):
        for w in weights:
            name = f"{slug}-latin-{w}-normal.woff2"
            copy(folder / name, VENDOR / "fonts" / name)
            css.append(f"@font-face {{ font-family: '{fam}'; font-style: normal; font-display: swap; "
                       f"font-weight: {w}; src: url(./{name}) format('woff2'); }}")
    (VENDOR / "fonts" / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    print("फाइल्स ठेवल्या:", VENDOR)


def backup(path: Path):
    bak = path.with_suffix(path.suffix + ".bak")
    if not bak.exists():
        shutil.copy2(path, bak)


def patch_files():
    for path, old, new in EDITS:
        if not path.exists():
            print(f"वगळले (फाइल नाही): {path}")
            continue
        data = path.read_bytes()
        if new in data and old not in data:
            print(f"आधीच केलेले: {path.name}")
            continue
        n = data.count(old)
        if n != 1:
            print(f"थांबलो: {path.name} मध्ये अपेक्षित 1 जुळणी, सापडल्या {n} (बदल केला नाही)")
            continue
        backup(path)
        path.write_bytes(data.replace(old, new))
        print(f"बदलले: {path.name}")

    # फॉन्ट: Google Fonts @import काढा, index.html मध्ये स्थानिक fonts.css जोडा
    css_path = SRC / "App.css"
    if css_path.exists():
        data = css_path.read_bytes()
        if GOOGLE_FONTS_IMPORT in data:
            backup(css_path)
            css_path.write_bytes(data.replace(GOOGLE_FONTS_IMPORT, b"/* Google Fonts @import removed: fonts are served from public/vendor/fonts */"))
            print("बदलले: App.css (Google Fonts @import काढला)")
        elif b"fonts.googleapis.com" in data:
            print("लक्ष द्या: App.css मध्ये fonts.googleapis.com अजून आहे, पण तो वेगळ्या रूपात आहे; हाताने काढा.")
        else:
            print("आधीच केलेले: App.css")
    html_path = PUBLIC / "index.html"
    if html_path.exists():
        data = html_path.read_bytes()
        if FONT_LINK not in data:
            marker = b"</head>"
            if data.count(marker) == 1:
                backup(html_path)
                nl = b"\r\n" if b"\r\n" in data else b"\n"
                html_path.write_bytes(data.replace(marker, b"    " + FONT_LINK + nl + marker))
                print("बदलले: index.html (स्थानिक fonts.css जोडले)")
            else:
                print("लक्ष द्या: index.html मध्ये </head> एकदाच सापडले नाही; हा ओळ हाताने जोडा:", FONT_LINK.decode())
        else:
            print("आधीच केलेले: index.html (fonts.css)")


def report():
    left = []
    needles = (b"cdn.jsdelivr.net", b"cdnjs.cloudflare.com", b"fonts.googleapis.com", b"fonts.gstatic.com", b"unpkg.com")
    for base in (PUBLIC / "index.html", SRC):
        files = [base] if base.is_file() else [p for p in base.rglob("*") if p.suffix in (".js", ".jsx", ".css", ".html") and "node_modules" not in p.parts]
        for f in files:
            try:
                data = f.read_bytes()
            except Exception:
                continue
            for n in needles:
                if n in data:
                    left.append((f, n.decode()))
    print("\nतपासणी - अजून बाकी असलेले बाहेरचे CDN/फॉन्ट संदर्भ:")
    if not left:
        print("  काहीही नाही")
    for f, n in left:
        print(f"  {f}: {n}")


def main():
    if not (ROOT / "package.json").exists() or not PUBLIC.exists() or not SRC.exists():
        sys.exit(f"{ROOT} हा frontend फोल्डर वाटत नाही (package.json, public, src हवे). frontend फोल्डरमधून चालवा.")
    tmp = Path(tempfile.mkdtemp(prefix="evaassets_"))
    try:
        pkgs = npm_pack(tmp)
        install_assets(pkgs)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    patch_files()
    report()
    print("\nपूर्ण. आता frontend restart (npm start) किंवा पुन्हा build करा.")


if __name__ == "__main__":
    main()
